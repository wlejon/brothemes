struct ThemeDef {
    const char* name;
    Color bg;
    Color fg;
    std::array<Color, 16> ansi;
};

Theme make_theme(const ThemeDef& def) {
    Theme t;
    t.metadata.name = def.name;
    t.ui.background = def.bg;
    t.ui.foreground = def.fg;
    t.ansi.colors = def.ansi;
    t.normalize();
    return t;
}

